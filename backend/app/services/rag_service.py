import re

from app.services.search_service import (
    search_similar_chunks,
    calculate_keyword_score
)

from app.services.gemini_service import (
    generate_answer
)

from app.core.database import db


# ============================================================
# CONFIGURATION
# ============================================================

SEARCH_RESULT_LIMIT = 8

MAX_ANCHORS = 2

MAX_CONTEXT_CHUNKS = 6

STRONG_ANCHOR_SCORE = 0.70

SECONDARY_ANCHOR_SCORE = 0.75

NEIGHBOR_KEYWORD_THRESHOLD = 0.20


# ============================================================
# REMOVE DUPLICATES
# ============================================================

def remove_duplicate_chunks(
    chunks: list[dict]
):
    """
    Remove duplicate chunks using document_id + chunk_index.
    """

    unique_chunks = []

    seen = set()

    for chunk in chunks:

        key = (
            chunk.get("document_id"),
            chunk.get("chunk_index")
        )

        if key in seen:

            continue

        seen.add(key)

        unique_chunks.append(
            chunk
        )

    return unique_chunks


# ============================================================
# QUESTION RELEVANCE
# ============================================================

def calculate_question_relevance(
    question: str,
    chunk: dict
):
    """
    Calculate overall relevance using the scores already
    generated by the search service.

    Semantic similarity has higher importance than
    keyword overlap.
    """

    semantic_score = chunk.get(
        "semantic_score",
        0.0
    )

    keyword_score = chunk.get(
        "keyword_score",
        0.0
    )

    return (
        semantic_score * 0.70
        +
        keyword_score * 0.30
    )


# ============================================================
# CONTINUATION DETECTION
# ============================================================

def looks_like_continuation(
    previous_text: str,
    current_text: str
):
    """
    Determine whether current_text is likely a continuation
    of previous_text.
    """

    if not current_text:

        return False

    current_text = current_text.strip()

    if not current_text:

        return False

    # --------------------------------------------------------
    # Lowercase beginning usually indicates continuation
    # --------------------------------------------------------

    if current_text[0].islower():

        return True

    # --------------------------------------------------------
    # Previous chunk ended without sentence punctuation
    # --------------------------------------------------------

    if previous_text:

        previous_text = previous_text.rstrip()

        if previous_text:

            if previous_text[-1] not in ".!?":

                return True

    # --------------------------------------------------------
    # Common continuation patterns
    # --------------------------------------------------------

    continuation_patterns = [

        r"^(and|or|but|also)\b",

        r"^(which|that|these|those)\b",

        r"^(such as|including)\b",

        r"^(for example)\b",

        r"^(in addition|however)\b"
    ]

    for pattern in continuation_patterns:

        if re.match(
            pattern,
            current_text,
            flags=re.IGNORECASE
        ):

            return True

    return False


# ============================================================
# FORMAT NEIGHBOR
# ============================================================

def format_neighbor_chunk(
    chunk: dict,
    question: str
):
    """
    Convert a raw MongoDB chunk into the same structure
    used by the RAG context system.
    """

    text = chunk.get(
        "text",
        ""
    )

    keyword_score = calculate_keyword_score(
        question,
        text
    )

    return {

        "chunk_id":
            str(
                chunk["_id"]
            ),

        "document_id":
            chunk.get(
                "document_id"
            ),

        "chunk_index":
            chunk.get(
                "chunk_index",
                0
            ),

        "page_number":
            chunk.get(
                "page_number"
            ),

        "text":
            text,

        "character_count":
            chunk.get(
                "character_count",
                len(text)
            ),

        "word_count":
            chunk.get(
                "word_count",
                len(text.split())
            ),

        "score":
            0.0,

        "semantic_score":
            0.0,

        "keyword_score":
            keyword_score,

        "contextual_boost":
            0.0,

        "is_neighbor":
            True
    }


# ============================================================
# FETCH INTELLIGENT NEIGHBORS
# ============================================================

def fetch_intelligent_neighbors(
    user_id: str,
    document_id: str,
    chunk_index: int,
    question: str,
    anchor_score: float,
    anchor_text: str
):
    """
    Retrieve useful neighboring chunks around a strong anchor.

    A neighboring chunk is included when it is either:

    - a continuation of the anchor, or
    - contains meaningful query keywords.
    """

    neighbors = []

    if anchor_score < STRONG_ANCHOR_SCORE:

        return neighbors

    # --------------------------------------------------------
    # Previous chunk
    # --------------------------------------------------------

    previous_chunk = db.document_chunks.find_one({

        "user_id":
            user_id,

        "document_id":
            document_id,

        "chunk_index":
            chunk_index - 1
    })

    # --------------------------------------------------------
    # Next chunk
    # --------------------------------------------------------

    next_chunk = db.document_chunks.find_one({

        "user_id":
            user_id,

        "document_id":
            document_id,

        "chunk_index":
            chunk_index + 1
    })

    # ========================================================
    # PREVIOUS CHUNK
    # ========================================================

    if previous_chunk:

        previous_text = previous_chunk.get(
            "text",
            ""
        )

        formatted_previous = format_neighbor_chunk(
            previous_chunk,
            question
        )

        previous_is_continuation = looks_like_continuation(
            previous_text,
            anchor_text
        )

        if (
            previous_is_continuation
            or
            formatted_previous["keyword_score"]
            >= NEIGHBOR_KEYWORD_THRESHOLD
        ):

            neighbors.append(
                formatted_previous
            )

    # ========================================================
    # NEXT CHUNK
    # ========================================================

    if next_chunk:

        next_text = next_chunk.get(
            "text",
            ""
        )

        formatted_next = format_neighbor_chunk(
            next_chunk,
            question
        )

        next_is_continuation = looks_like_continuation(
            anchor_text,
            next_text
        )

        if (
            next_is_continuation
            or
            formatted_next["keyword_score"]
            >= NEIGHBOR_KEYWORD_THRESHOLD
        ):

            neighbors.append(
                formatted_next
            )

    return neighbors


# ============================================================
# SELECT ANCHORS
# ============================================================

def select_anchors(
    retrieved_chunks: list[dict]
):
    """
    Select the strongest chunks to serve as the main
    context anchors.

    The primary anchor must have meaningful relevance.
    A secondary anchor requires substantially stronger
    evidence.
    """

    if not retrieved_chunks:

        return []

    ranked = sorted(

        retrieved_chunks,

        key=lambda chunk:
            calculate_question_relevance(
                "",
                chunk
            ),

        reverse=True
    )

    if not ranked:

        return []

    # --------------------------------------------------------
    # Primary anchor
    # --------------------------------------------------------

    primary = ranked[0]

    primary_score = primary.get(
        "score",
        0.0
    )

    primary_semantic = primary.get(
        "semantic_score",
        0.0
    )

    primary_keyword = primary.get(
        "keyword_score",
        0.0
    )

    # --------------------------------------------------------
    # Do not create context from an extremely weak result.
    #
    # Search service already filters candidates, but this
    # provides an additional RAG-level safety check.
    # --------------------------------------------------------

    if (
        primary_score < 0.40
        and
        primary_semantic < 0.35
        and
        primary_keyword < 0.50
    ):

        return []

    anchors = [
        primary
    ]

    # --------------------------------------------------------
    # Secondary anchor
    # --------------------------------------------------------

    for candidate in ranked[1:]:

        if len(anchors) >= MAX_ANCHORS:

            break

        score = candidate.get(
            "score",
            0.0
        )

        semantic_score = candidate.get(
            "semantic_score",
            0.0
        )

        keyword_score = candidate.get(
            "keyword_score",
            0.0
        )

        if (
            score >= SECONDARY_ANCHOR_SCORE
            and
            semantic_score >= 0.70
            and
            keyword_score >= 0.50
        ):

            anchors.append(
                candidate
            )

    return anchors


# ============================================================
# ASSEMBLE CONTEXT
# ============================================================

def assemble_context(
    user_id: str,
    question: str,
    retrieved_chunks: list[dict]
):
    """
    Build the final set of document chunks that will be
    provided to Gemini.
    """

    if not retrieved_chunks:

        return []

    # --------------------------------------------------------
    # Remove duplicates
    # --------------------------------------------------------

    retrieved_chunks = remove_duplicate_chunks(
        retrieved_chunks
    )

    # --------------------------------------------------------
    # Select anchors
    # --------------------------------------------------------

    anchors = select_anchors(
        retrieved_chunks
    )

    if not anchors:

        return []

    context_chunks = []

    # --------------------------------------------------------
    # Add anchors first
    # --------------------------------------------------------

    for anchor in anchors:

        context_chunks.append(
            anchor
        )

    # --------------------------------------------------------
    # Add intelligent neighbors
    # --------------------------------------------------------

    for anchor in anchors:

        anchor_text = anchor.get(
            "text",
            ""
        )

        neighbors = fetch_intelligent_neighbors(

            user_id=user_id,

            document_id=anchor.get(
                "document_id"
            ),

            chunk_index=anchor.get(
                "chunk_index",
                0
            ),

            question=question,

            anchor_score=anchor.get(
                "score",
                0
            ),

            anchor_text=anchor_text
        )

        context_chunks.extend(
            neighbors
        )

    # --------------------------------------------------------
    # Remove duplicates again
    # --------------------------------------------------------

    context_chunks = remove_duplicate_chunks(
        context_chunks
    )

    # --------------------------------------------------------
    # Rank anchors first, then supporting chunks
    #
    # This ensures the most important chunks are retained
    # when MAX_CONTEXT_CHUNKS is reached.
    # --------------------------------------------------------

    anchor_keys = {

        (
            chunk.get("document_id"),
            chunk.get("chunk_index")
        )

        for chunk in anchors
    }

    context_chunks.sort(

        key=lambda chunk: (

            0
            if (
                chunk.get("document_id"),
                chunk.get("chunk_index")
            )
            in anchor_keys
            else 1,

            -chunk.get(
                "score",
                0
            )
        )
    )

    # --------------------------------------------------------
    # Limit context size
    # --------------------------------------------------------

    context_chunks = context_chunks[
        :MAX_CONTEXT_CHUNKS
    ]

    # --------------------------------------------------------
    # Restore document order
    #
    # Gemini receives the selected context in natural
    # document order rather than relevance order.
    # --------------------------------------------------------

    context_chunks.sort(

        key=lambda chunk: (

            chunk.get(
                "document_id",
                ""
            ),

            chunk.get(
                "chunk_index",
                0
            )
        )
    )

    return context_chunks


# ============================================================
# BUILD CONTEXT
# ============================================================

def build_context(
    chunks: list[dict]
):
    """
    Convert selected chunks into the context format
    provided to Gemini.
    """

    context_parts = []

    for index, chunk in enumerate(
        chunks,
        start=1
    ):

        page_number = chunk.get(
            "page_number"
        )

        if page_number is not None:

            source_label = (

                f"[Context {index} | "
                f"Page {page_number} | "
                f"Chunk {chunk['chunk_index']}]"
            )

        else:

            source_label = (

                f"[Context {index} | "
                f"Chunk {chunk['chunk_index']}]"
            )

        context_parts.append(

            f"{source_label}\n"
            f"{chunk['text']}"
        )

    return "\n\n".join(
        context_parts
    )


# ============================================================
# BUILD SOURCES
# ============================================================

def build_sources(
    context_chunks: list[dict]
):
    """
    Build source metadata returned to the frontend.
    """

    sources = []

    seen_sources = set()

    for chunk in context_chunks:

        source_key = (

            chunk.get(
                "document_id"
            ),

            chunk.get(
                "chunk_index"
            )
        )

        if source_key in seen_sources:

            continue

        seen_sources.add(
            source_key
        )

        text = chunk.get(
            "text",
            ""
        )

        sources.append({

            "document_id":
                chunk.get(
                    "document_id"
                ),

            "chunk_id":
                chunk.get(
                    "chunk_id"
                ),

            "chunk_index":
                chunk.get(
                    "chunk_index"
                ),

            "page_number":
                chunk.get(
                    "page_number"
                ),

            "score":
                chunk.get(
                    "score",
                    0
                ),

            "semantic_score":
                chunk.get(
                    "semantic_score",
                    0
                ),

            "keyword_score":
                chunk.get(
                    "keyword_score",
                    0
                ),

            "contextual_boost":
                chunk.get(
                    "contextual_boost",
                    0
                ),

            "is_neighbor":
                chunk.get(
                    "is_neighbor",
                    False
                ),

            "text":
                text,

            "character_count":
                chunk.get(
                    "character_count",
                    len(text)
                ),

            "word_count":
                chunk.get(
                    "word_count",
                    len(text.split())
                )
        })

    return sources


# ============================================================
# ANSWER QUESTION
# ============================================================

def answer_question(
    user_id: str,
    question: str,
    document_id: str | None = None
):
    """
    Answer a question using document-grounded RAG.

    Pipeline:

    Question
       ↓
    Hybrid Search
       ↓
    Anchor Selection
       ↓
    Neighbor Retrieval
       ↓
    Context Assembly
       ↓
    Gemini
       ↓
    Answer + Sources
    """

    if not isinstance(
        question,
        str
    ):

        return {

            "answer":
                "Please enter a question.",

            "sources":
                []
        }

    question = question.strip()

    if not question:

        return {

            "answer":
                "Please enter a question.",

            "sources":
                []
        }

    # --------------------------------------------------------
    # Retrieve candidate chunks
    # --------------------------------------------------------

    retrieved_chunks = search_similar_chunks(

        user_id=user_id,

        query=question,

        limit=SEARCH_RESULT_LIMIT,

        document_id=document_id
    )

    if not retrieved_chunks:

        return {

            "answer": (
                "I couldn't find relevant "
                "information in your documents."
            ),

            "sources":
                []
        }

    # --------------------------------------------------------
    # Assemble intelligent context
    # --------------------------------------------------------

    context_chunks = assemble_context(

        user_id=user_id,

        question=question,

        retrieved_chunks=retrieved_chunks
    )

    if not context_chunks:

        return {

            "answer": (
                "I couldn't find relevant "
                "information in your documents."
            ),

            "sources":
                []
        }

    # --------------------------------------------------------
    # Build Gemini context
    # --------------------------------------------------------

    context = build_context(
        context_chunks
    )

    # --------------------------------------------------------
    # Gemini prompt
    # --------------------------------------------------------

    prompt = f"""
You are DocuMind AI, a document
question-answering assistant.

Answer the user's question using ONLY
the document context provided below.

Do not use outside knowledge.
Do not invent information.

If the answer cannot be found in the
provided context, say exactly:

"I couldn't find that information
in your documents."

Rules:

1. Answer the question directly.

2. Use only information supported
   by the document context.

3. Do not make assumptions.

4. Do not invent facts.

5. Consecutive chunks may contain
   continuation of the same section.
   Combine them when necessary.

6. Preserve important terminology
   from the document.

7. Ignore unrelated information.

8. Keep the answer clear and concise.

9. Do not mention internal context
   numbers unless necessary.

DOCUMENT CONTEXT:

{context}

USER QUESTION:

{question}

ANSWER:
"""

    # --------------------------------------------------------
    # Generate answer
    # --------------------------------------------------------

    try:

        answer = generate_answer(
            prompt
        )

    except Exception as error:

        print(
            "RAG answer generation failed:"
        )

        print(error)

        return {

            "answer": (
                "I couldn't generate an answer "
                "from your documents."
            ),

            "sources":
                []
        }

    if not answer:

        answer = (
            "I couldn't generate an answer "
            "from your documents."
        )

    # --------------------------------------------------------
    # Build sources
    # --------------------------------------------------------

    sources = build_sources(
        context_chunks
    )

    return {

        "answer":
            answer.strip(),

        "sources":
            sources
    }


# ============================================================
# RETRIEVE DOCUMENT CONTEXT ONLY
# ============================================================

def retrieve_document_context(
    user_id: str,
    question: str,
    document_id: str | None = None
):
    """
    Retrieve relevant document context without calling Gemini.

    This is used by conversational RAG.

    The chat service can combine this context with
    conversation history and make exactly one Gemini call.
    """

    if not isinstance(
        question,
        str
    ):

        return {

            "context_chunks":
                [],

            "sources":
                []
        }

    question = question.strip()

    if not question:

        return {

            "context_chunks":
                [],

            "sources":
                []
        }

    # --------------------------------------------------------
    # Retrieve candidates
    # --------------------------------------------------------

    retrieved_chunks = search_similar_chunks(

        user_id=user_id,

        query=question,

        limit=SEARCH_RESULT_LIMIT,

        document_id=document_id
    )

    if not retrieved_chunks:

        return {

            "context_chunks":
                [],

            "sources":
                []
        }

    # --------------------------------------------------------
    # Assemble context
    # --------------------------------------------------------

    context_chunks = assemble_context(

        user_id=user_id,

        question=question,

        retrieved_chunks=retrieved_chunks
    )

    if not context_chunks:

        return {

            "context_chunks":
                [],

            "sources":
                []
        }

    # --------------------------------------------------------
    # Build sources
    # --------------------------------------------------------

    sources = build_sources(
        context_chunks
    )

    return {

        "context_chunks":
            context_chunks,

        "sources":
            sources
    }